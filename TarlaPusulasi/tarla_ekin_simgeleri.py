def draw(canvas, name, x, y, color):
    paths, ellipses = ICONS[name]
    for path in paths:
        points = [value + (x if i % 2 == 0 else y) - 12 for i, value in enumerate(path)]
        canvas.create_line(*points, fill=color, width=1.5, capstyle="round", joinstyle="round",
                           tags="crop_icon")
    for cx, cy, rx, ry in ellipses:
        cx, cy = x + cx - 12, y + cy - 12
        canvas.create_oval(cx - rx, cy - ry, cx + rx, cy + ry, outline=color, width=1.5,
                           tags="crop_icon")
